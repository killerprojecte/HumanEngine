//go:build web_read_candidate

// Package host provides native stream, cancellation and timer facilities to the
// web-read guest. It deliberately has no fallback HTTP client: Fetch must honor
// requestPublicResource semantics, including raw headers and public DNS pinning.
package host

import (
	"context"
	"encoding/json"
	"errors"
	"sync"
	"time"

	"github.com/killerprojecte/HumanEngine/backend/internal/toolresults"
)

type CacheResult func(context.Context, toolresults.Source, toolresults.Options) (toolresults.Result, error)
type Resource struct {
	Source                toolresults.Source
	StatusCode            int
	Headers               map[string]any
	RawHeaders            []string
	FinalURL, ContentType string
	// Finish destroys the stream and waits for outstanding native I/O. The
	// physical-work lease is held until Finish returns, including on cache failure.
	Finish func()
}
type Fetch func(context.Context, json.RawMessage, time.Duration) (Resource, error)
type Ports struct {
	Life                   context.Context
	Config                 json.RawMessage
	BeginWork              func() (func(), bool)
	Current                func() bool
	Lifetime               func(context.Context, context.Context) (context.Context, func())
	CallGuestWithAdmission func(context.Context, context.Context, []byte) ([]byte, error)
	Fetch                  Fetch
}
type Service struct {
	ports  Ports
	mu     sync.Mutex
	active int
}

func NewCandidate(p Ports) (*Service, error) {
	if p.Life == nil || p.BeginWork == nil || p.Current == nil || p.Lifetime == nil || p.CallGuestWithAdmission == nil || p.Fetch == nil {
		return nil, errors.New("web_read_runtime_ports_missing")
	}
	return &Service{ports: p}, nil
}
func (s *Service) guest(wait context.Context, operation string, in map[string]any) (json.RawMessage, error) {
	in["operation"] = operation
	raw, e := json.Marshal(in)
	if e != nil {
		return nil, e
	}
	return s.ports.CallGuestWithAdmission(wait, s.ports.Life, raw)
}
func (s *Service) Registrations() (json.RawMessage, error) {
	return s.guest(s.ports.Life, "registrations", map[string]any{})
}

// Execute is the manager-facing continuation, not a standalone WebReadService
// clone. The manager discards cancelled turns; its callback may settle before
// native/guest work drains. executePhysical retains the original work lease.
func (s *Service) Execute(ctx context.Context, tool string, input json.RawMessage, cache CacheResult) (json.RawMessage, error) {
	input = append(json.RawMessage(nil), input...)
	type answer struct {
		value json.RawMessage
		err   error
	}
	result := make(chan answer, 1)
	go s.executePhysical(ctx, tool, input, cache, func(value json.RawMessage, err error) { result <- answer{value, err} })
	select {
	case out := <-result:
		return out.value, out.err
	case <-ctx.Done():
		return nil, ctx.Err()
	case <-s.ports.Life.Done():
		return nil, s.ports.Life.Err()
	}
}
func (s *Service) executePhysical(ctx context.Context, tool string, input json.RawMessage, cache CacheResult, settle func(json.RawMessage, error)) (value json.RawMessage, resultErr error) {
	done, ok := s.ports.BeginWork()
	if !ok {
		settle(nil, context.Canceled)
		return nil, context.Canceled
	}
	defer done()
	var physicalFinish func()
	defer func() {
		if physicalFinish != nil {
			physicalFinish()
		}
	}()
	defer func() { settle(value, resultErr) }()
	if !s.ports.Current() || s.ports.Life.Err() != nil {
		return nil, context.Canceled
	}
	combined, cancel := s.ports.Lifetime(ctx, s.ports.Life)
	defer cancel()
	s.mu.Lock()
	raw, err := s.guest(combined, "plan", map[string]any{"tool": tool, "input": input, "config": s.ports.Config, "active": s.active, "cancelled": combined.Err() != nil})
	var plan struct {
		Result          json.RawMessage `json:"result"`
		Request         json.RawMessage `json:"request"`
		TimeoutMS       float64         `json:"timeoutMs"`
		Action          bool            `json:"action"`
		CancelledResult json.RawMessage `json:"cancelledResult"`
		TimeoutResult   json.RawMessage `json:"timeoutResult"`
	}
	if err == nil {
		err = json.Unmarshal(raw, &plan)
	}
	if err != nil || len(plan.Result) != 0 {
		s.mu.Unlock()
		return plan.Result, err
	}
	if len(plan.Request) == 0 {
		s.mu.Unlock()
		return nil, errors.New("invalid_web_read_policy")
	}
	if combined.Err() != nil {
		s.mu.Unlock()
		return plan.CancelledResult, nil
	}
	s.active++
	s.mu.Unlock()
	defer func() { s.mu.Lock(); s.active--; s.mu.Unlock() }()
	timeout := time.Duration(plan.TimeoutMS) * time.Millisecond
	timed, cancelTimeout := context.WithTimeout(combined, timeout)
	defer cancelTimeout()
	errorResult := func(err error) (json.RawMessage, error) {
		// These continuations were generated by the guest at source admission.
		// Cancellation never needs to queue another call behind unfinished work.
		if combined.Err() != nil {
			return plan.CancelledResult, nil
		}
		if timed.Err() == context.DeadlineExceeded {
			return plan.TimeoutResult, nil
		}
		result, callErr := s.guest(timed, "error", map[string]any{"tool": tool, "message": err.Error(), "typeError": isTypeError(err), "cancelled": combined.Err() != nil, "timedOut": timed.Err() == context.DeadlineExceeded, "action": plan.Action, "requestStarted": true})
		if callErr != nil {
			if combined.Err() != nil {
				return plan.CancelledResult, nil
			}
			if timed.Err() == context.DeadlineExceeded {
				return plan.TimeoutResult, nil
			}
		}
		return result, callErr
	}
	resource, err := s.ports.Fetch(timed, plan.Request, timeout)
	// Fetch may settle before DNS/guest physical work drains; those jobs own
	// separate leases. On response success this service joins its stream only
	// after logical settlement and active-slot release, as source destroy() does.
	if err != nil {
		return errorResult(err)
	}
	if resource.Finish == nil {
		return nil, errors.New("web_read_stream_lifetime_missing")
	}
	physicalFinish = resource.Finish
	encoding := resource.Headers["content-encoding"]
	policy, err := s.guest(timed, "cachePolicy", map[string]any{"contentType": resource.ContentType, "contentEncoding": encoding})
	if err != nil {
		return errorResult(err)
	}
	var options struct {
		Encoding     toolresults.Encoding `json:"encoding"`
		PreviewBytes float64              `json:"previewBytes"`
		ContentType  string               `json:"contentType"`
	}
	if err = json.Unmarshal(policy, &options); err != nil {
		return nil, err
	}
	if cache == nil {
		return errorResult(errors.New("tool_result_cache_missing"))
	}
	body, err := cache(timed, resource.Source, toolresults.Options{Encoding: options.Encoding, PreviewBytes: &options.PreviewBytes, ContentType: &options.ContentType})
	if err != nil {
		return errorResult(err)
	}
	result, callErr := s.guest(timed, "response", map[string]any{"tool": tool, "config": s.ports.Config, "httpStatus": resource.StatusCode, "headers": resource.Headers, "rawHeaders": resource.RawHeaders, "sourceUrl": resource.FinalURL, "contentEncoding": encoding, "body": body})
	if callErr != nil {
		return errorResult(callErr)
	}
	return result, nil
}

// A source-compatible transport marks JavaScript TypeError-equivalent URL
// failures without leaking URLs or private headers into diagnostics.
type typeError interface{ TypeError() bool }

func isTypeError(err error) bool { var e typeError; return errors.As(err, &e) && e.TypeError() }
