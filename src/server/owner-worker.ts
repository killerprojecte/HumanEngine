import { parentPort } from 'node:worker_threads'
import { getEngine, closeEngine, startEngineDisposal } from './owner-runtime.ts'
import { startupDiagnostic } from '../diagnostics/startup.ts'
import { bindRequestId } from '../diagnostics/errors.ts'
import { readBody } from './worker-rpc.ts'
import { fetchWithPublicationProof } from '../api.ts'
import { installOwnerErrorCapture } from './owner-errors.ts'
if (!parentPort) throw new Error('worker_parent_required')
installOwnerErrorCapture()
const port = parentPort
const operations = new Map<number, AbortController>()
let closing = false
try {
  const runtime = await getEngine()
  port.on('message', async (message) => {
    if (message.release !== undefined) return
    if (message.cancel !== undefined) {
      operations.get(message.cancel)?.abort()
      return
    }
    const { id, op, payload } = message
    if (op === 'close') {
      closing = true
      for (const controller of operations.values()) controller.abort()
      // Some routes use subsystem/plugin signals rather than request.signal.
      // Start their cancellation now, but do not close SQLite under route cleanup.
      const disposal = startEngineDisposal()
      void disposal.catch(() => {}) // closeEngine observes the same cached failure below.
      try {
        while (operations.size) await new Promise((resolve) => setTimeout(resolve, 10))
        await closeEngine()
        port.postMessage({ id, result: null })
      } catch {
        port.postMessage({ id, error: true })
      }
      return
    }
    if (closing || op !== 'fetch' || !(payload?.body instanceof Uint8Array)) {
      port.postMessage({ id, error: true })
      return
    }
    const controller = new AbortController()
    operations.set(id, controller)
    try {
      const request = new Request(payload.url, {
        method: payload.method,
        headers: payload.headers,
        signal: controller.signal,
        ...(payload.body.byteLength ? { body: payload.body as Uint8Array<ArrayBuffer> } : {}),
      })
      // This field is generated by the HTTP host, never copied from request headers.
      if (typeof payload.requestId === 'string') bindRequestId(request, payload.requestId)
      const { response, observedHead } = await fetchWithPublicationProof(runtime.app, request)
      // Never authorize bytes by reading a newer head after asynchronous serialization.
      const body = await readBody(response.body, { signal: controller.signal })
      if (controller.signal.aborted) throw new Error('request_aborted')
      if (!observedHead) throw new Error('response_proof_missing')
      port.postMessage(
        {
          id,
          result: { status: response.status, headers: [...response.headers], body, observedHead },
        },
        [body.buffer as ArrayBuffer],
      )
    } catch {
      port.postMessage({ id, error: true })
    } finally {
      operations.delete(id)
    }
  })
  port.postMessage({ ready: true })
} catch (error) {
  port.postMessage({ startupError: startupDiagnostic(error).code })
}
